"""Write the run manifest: what ran, from what, with what.

Every ``generate_all`` run writes ``run_manifest.json`` next to its outputs.
The manifest is the one artefact allowed to differ between runs: it records
the commit hash, timestamp, Python and package versions, the seeds used, and
the SHA-256 of every data input, so a non-empty diff between two runs' outputs
can be traced to a cause. The outputs themselves carry no timestamp and are
byte-identical for the same seed.
"""

from __future__ import annotations

import hashlib
import json
import os
import platform
import subprocess
import sys
from datetime import datetime, timezone

from src.seeds import DEFAULT_SEED, DEFAULT_SCENES, SENSITIVITY_SEEDS

REPO_ROOT = os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
)

# The packages whose versions decide the outputs. dev tools are not listed:
# they cannot change a generated byte.
CORE_PACKAGES = [
    "numpy",
    "matplotlib",
    "pandas",
    "pyyaml",
    "tabulate",
    "jsonschema",
    "graphviz",
]

# Every non-code input the pipeline or its tests read.
INPUT_GLOBS = [
    ("gsn", ".gsn.yaml"),
    ("configs", ".yaml"),
    (os.path.join("data", "carla_configs"), ".yaml"),
]


def _commit_hash() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown (not a git checkout)"


def _package_versions() -> dict[str, str]:
    from importlib import metadata

    versions = {}
    for name in CORE_PACKAGES:
        try:
            versions[name] = metadata.version(name)
        except metadata.PackageNotFoundError:
            versions[name] = "not installed"
    return versions


def _input_hashes() -> dict[str, str]:
    hashes = {}
    for directory, suffix in INPUT_GLOBS:
        full = os.path.join(REPO_ROOT, directory)
        if not os.path.isdir(full):
            continue
        for name in sorted(os.listdir(full)):
            if not name.endswith(suffix):
                continue
            path = os.path.join(full, name)
            with open(path, "rb") as handle:
                digest = hashlib.sha256(handle.read()).hexdigest()
            hashes[f"{directory}/{name}".replace(os.sep, "/")] = digest
    return hashes


def write_manifest(output_dir: str, seed: int, scenes: int) -> str:
    """Write run_manifest.json into ``output_dir``; return its path."""
    manifest = {
        "commit": _commit_hash(),
        "run_at": datetime.now(timezone.utc).isoformat(),
        "python": sys.version,
        "platform": platform.platform(),
        "packages": _package_versions(),
        "seeds": {
            "run_seed": seed,
            "scenes_per_weather": scenes,
            "default_seed": DEFAULT_SEED,
            "default_scenes": DEFAULT_SCENES,
            "sensitivity_seeds": SENSITIVITY_SEEDS,
        },
        "input_hashes": _input_hashes(),
    }
    path = os.path.join(output_dir, "run_manifest.json")
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(manifest, handle, indent=2)
        handle.write("\n")
    return path
